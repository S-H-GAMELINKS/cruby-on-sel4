#!/usr/bin/env ruby
# frozen_string_literal: true
#
# Turn the Shinonome 16 dot BDF fonts into a C table for the framebuffer console.
#
# Shinonome is a 16 dot Japanese bitmap family: full width characters are 16x16
# and half width ones 8x16. Those are exactly two cells and one cell of the
# console's 8x16 grid, so every glyph is drawn at the console's own scale with no
# padding and no distortion.
#
#   http://openlab.ring.gr.jp/efont/shinonome/
#   "このアーカイブに含まれるすべてのフォントデータ、ドキュメント、スクリプ
#    ト類はすべて Public Domain で提供されています。... 自由な改造、他フォー
#    マットへの変換、組込み、再配布を行うことができます。"
#
# Three files go in, each for a different part of the table:
#
#   shnmk16.bdf    JIS X 0208: kanji, kana and the full width symbols
#   shnm8x16r.bdf  JIS X 0201: half width katakana, and the yen sign and
#                  overline that JIS puts where ASCII has \ and ~
#   shnm8x16a.bdf  ISO 8859-1: the Latin-1 symbols and letters
#
# ASCII is deliberately left out. The console draws 0x20 to 0x7e from Terminus,
# and a Ruby prompt is mostly ASCII.
#
# The BDF files are not encoded in Unicode. JIS X 0208 codes are mapped through
# EUC-JP, and also through CP51932 where that disagrees -- for the wave dash,
# the double vertical line and a handful of others the two give different code
# points, and text from either world should find its glyph.
#
# Where a code point has both a half width and a full width glyph, as some of
# Latin-1 does, the half width one wins: East Asian Width calls those characters
# ambiguous, and Reline and slides.rb both count them as one column.
#
# Usage:
#   ruby tools/generate-shinonome.rb shnmk16.bdf shnm8x16r.bdf shnm8x16a.bdf \
#     > src/console/font_shinonome.c

FONT_HEIGHT = 16

# Read a BDF file into { encoding => [advance, rows] }, each row a 16 bit
# integer with the leftmost pixel in the most significant bit.
def read_bdf(path)
  glyphs = {}
  ascent = nil
  encoding = nil
  bbx = nil
  dwidth = nil
  bitmap = nil

  File.foreach(path, encoding: 'BINARY') do |line|
    line = line.strip

    case line
    when /\AFONT_ASCENT\s+(\d+)\z/
      ascent = Regexp.last_match(1).to_i
    when /\AENCODING\s+(-?\d+)\z/
      encoding = Regexp.last_match(1).to_i
    when /\ADWIDTH\s+(-?\d+)\s+(-?\d+)\z/
      dwidth = Regexp.last_match(1).to_i
    when /\ABBX\s+(\d+)\s+(\d+)\s+(-?\d+)\s+(-?\d+)\z/
      bbx = Regexp.last_match.captures.map(&:to_i)
    when 'BITMAP'
      bitmap = []
    when 'ENDCHAR'
      if encoding && bbx && bitmap && ascent
        width, height, xoff, yoff = bbx
        # BDF trims each glyph to its ink; put it back in the full box.
        top = ascent - (height + yoff)
        bytes = (width + 7) / 8
        rows = Array.new(FONT_HEIGHT, 0)

        bitmap.first(height).each_with_index do |hex, source_y|
          target_y = top + source_y
          next if target_y.negative? || target_y >= FONT_HEIGHT

          bits = hex.to_i(16)
          width.times do |source_x|
            target_x = xoff + source_x
            next if target_x.negative? || target_x >= 16
            # Each row is padded to whole bytes, from the left.
            next if (bits & (1 << ((bytes * 8) - 1 - source_x))).zero?

            rows[target_y] |= 1 << (15 - target_x)
          end
        end

        glyphs[encoding] = [dwidth, rows]
      end

      encoding = nil
      bbx = nil
      dwidth = nil
      bitmap = nil
    else
      bitmap << line if bitmap && !line.empty?
    end
  end

  glyphs
end

# The Unicode code points a JIS X 0208 code stands for.
def jisx0208_to_unicode(code)
  euc = [(code >> 8) | 0x80, (code & 0xff) | 0x80].pack('C*')
  %w[EUC-JP CP51932].filter_map do |name|
    euc.dup.force_encoding(name).encode('UTF-8').ord
  rescue EncodingError
    nil
  end.uniq
end

def jisx0201_to_unicode(code)
  case code
  when 0x5c then 0x00a5
  when 0x7e then 0x203e
  when 0xa1..0xdf then 0xff61 + (code - 0xa1)
  end
end

kanji_path, jisx0201_path, latin1_path = ARGV
abort "usage: #{$PROGRAM_NAME} shnmk16.bdf shnm8x16r.bdf shnm8x16a.bdf" unless latin1_path

# codepoint => [wide, rows]
table = {}

read_bdf(kanji_path).each do |code, (_advance, rows)|
  jisx0208_to_unicode(code).each do |codepoint|
    next if codepoint <= 0x7f || codepoint > 0xffff

    table[codepoint] = [1, rows]
  end
end

read_bdf(jisx0201_path).each do |code, (_advance, rows)|
  codepoint = jisx0201_to_unicode(code)
  table[codepoint] = [0, rows] if codepoint
end

read_bdf(latin1_path).each do |code, (_advance, rows)|
  table[code] = [0, rows] if code >= 0xa0 && code <= 0xff
end

abort 'no glyphs found' if table.empty?

puts <<~HEADER
  /*
   * Generated by tools/generate-shinonome.rb -- do not edit.
   *
   * Shinonome Gothic 16 (shnmk16, shnm8x16r, shnm8x16a), /efont/ project.
   * Public Domain: "自由な改造、他フォーマットへの変換、組込み、再配布を行う
   * ことができます。同時に、これらはすべて完全に無保証です。"
   * http://openlab.ring.gr.jp/efont/shinonome/
   *
   * Sorted by code point so that lookup can bisect. Sixteen rows of sixteen
   * pixels, two bytes per row with the left byte first, most significant bit
   * leftmost; a half width glyph uses only the left byte of each row.
   */

  #include "console.h"

  const console_glyph_t console_shinonome[] = {
HEADER

table.keys.sort.each do |codepoint|
  wide, rows = table[codepoint]
  bytes = rows.flat_map { |row| [row >> 8, row & 0xff] }.map { |b| format('0x%02x', b) }.join(', ')
  puts format('    { 0x%04x, %d, { %s } },', codepoint, wide, bytes)
end

puts '};'
puts
puts "const size_t console_shinonome_count = #{table.size};"

warn "#{table.size} glyphs, #{table.count { |_, (w, _)| w == 1 }} full width"
